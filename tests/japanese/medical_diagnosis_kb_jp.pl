% メイン診断ルール
診断(患者症状, 患者年齢, 患者既往歴, 診断リスト) :-
    findall(
        [疾患名, 信頼度],
        (
            疾患(疾患名),
            信頼度計算(疾患名, 患者症状, 患者年齢, 患者既往歴, 信頼度),
            信頼度 > 0.1
        ),
        未ソートリスト
    ),
    sort(2, @>=, 未ソートリスト, 診断リスト).

% 信頼度計算
信頼度計算(疾患名, 症状リスト, 年齢, 既往歴, 最終信頼度) :-
    症状マッチスコア(疾患名, 症状リスト, 基本スコア),
    年齢リスク要因(疾患名, 年齢, 年齢要因),
    既往歴リスク要因(疾患名, 既往歴, 既往歴要因),
    最終信頼度 is 基本スコア * 年齢要因 * 既往歴要因.

% 症状マッチスコア計算
症状マッチスコア(疾患名, 症状リスト, スコア) :-
    findall(
        確率,
        (
            member(症状, 症状リスト),
            疾患症状(疾患名, 症状, 確率)
        ),
        マッチした確率
    ),
    length(マッチした確率, マッチ数),
    (マッチ数 > 0 ->
        sum_list(マッチした確率, 合計),
        スコア is 合計 / マッチ数
    ;
        スコア = 0
    ).

% 年齢リスク要因
年齢リスク要因(疾患名, 年齢, 要因) :-
    年齢カテゴリ(年齢, カテゴリ),
    (リスク要因(カテゴリ, 疾患名, 要因) -> true ; 要因 = 1.0).

% 既往歴リスク要因
既往歴リスク要因(疾患名, 既往歴, 要因) :-
    findall(
        倍率,
        (
            member(条件, 既往歴),
            リスク要因(条件, 疾患名, 倍率)
        ),
        倍率リスト
    ),
    (倍率リスト = [] ->
        要因 = 1.0
    ;
        リスト乗算(倍率リスト, 要因)
    ).

% 補助述語
リスト乗算([], 1).
リスト乗算([先頭|残り], 結果) :-
    リスト乗算(残り, 残り結果),
    結果 is 先頭 * 残り結果.

% 推奨検査の決定
推奨検査(疾患名, 信頼度, 検査リスト) :-
    信頼度 > 0.6,
    疾患検査(疾患名, 検査リスト).

疾患検査(溶連菌感染, [迅速溶連菌検査, のど培養]).
疾患検査(肺炎, [胸部レントゲン, 血液検査]).
疾患検査(新型コロナ, [ＰＣＲ検査, 抗原検査]).
疾患検査(インフルエンザ, [インフルエンザ迅速検査]).
疾患検査(風邪, [特定検査なし]).

% 緊急度評価
緊急度レベル(症状リスト, 年齢, 既往歴, レベル) :-
    member(息切れ, 症状リスト),
    年齢 > 60,
    レベル = 高.
緊急度レベル(症状リスト, _, 既往歴, レベル) :-
    member(糖尿病, 既往歴),
    member(発熱, 症状リスト),
    レベル = 中.
緊急度レベル(_, _, _, 低).

% クエリ例のインターフェース
患者診断(症状リスト, 年齢, 既往歴, 結果) :-
    診断(症状リスト, 年齢, 既往歴, 診断リスト),
    緊急度レベル(症状リスト, 年齢, 既往歴, 緊急度),
    findall(
        [疾患名, 検査リスト],
        (
            member([疾患名, 信頼度], 診断リスト),
            推奨検査(疾患名, 信頼度, 検査リスト)
        ),
        検査推奨
    ),
    結果 = [診断結果(診断リスト), 緊急度(緊急度), 検査(検査推奨)].

